const {test,expect}=require('@playwright/test');
test('render isometric 3.0 retains static canvas and only draws dirty actors',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/');
 await page.locator('#startBtn').click();
 await page.waitForTimeout(320);
 const initial=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 expect(initial.staticBuilds).toBeGreaterThan(0);
 const layers=await page.locator('#game-wrap canvas').count();
 expect(layers).toBeGreaterThanOrEqual(3);
 await page.waitForTimeout(650);
 const next=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 expect(next.staticBuilds).toBe(initial.staticBuilds);
 expect(next.actorFrames).toBeGreaterThan(0);
 expect(next.lastClearRatio).toBeLessThan(.50);
 expect(next.spriteCache).toBeGreaterThan(0);
 const a=await page.locator('#world').getAttribute('style');
 await page.keyboard.down('d');await page.waitForTimeout(180);await page.keyboard.up('d');
 const b=await page.locator('#world').getAttribute('style');
 expect(a).not.toBe(b);
 const after=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 expect(after.staticBuilds).toBeLessThanOrEqual(next.staticBuilds+3);
 await page.screenshot({path:'test-results/v3-street.png',fullPage:true});
 await page.evaluate(()=>window.DeadCountyDebug.teleport(60,62));
 await page.waitForTimeout(120);
 const tele=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 expect(tele.staticBuilds).toBeGreaterThan(after.staticBuilds);
 await page.screenshot({path:'test-results/v3-interior.png',fullPage:true});
 expect(errors).toEqual([]);
});
test('mobile no full-screen repaint during idle gameplay',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/');await page.tap('#startBtn');
 await page.waitForTimeout(350);
 const before=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 await page.waitForTimeout(400);
 const after=await page.evaluate(()=>window.DeadCountyDebug.getMetrics());
 expect(after.staticBuilds).toBe(before.staticBuilds);
 expect(after.buffer[0]).toBeGreaterThan(360);
 expect(after.lastClearRatio).toBeLessThan(.45);
 await page.screenshot({path:'test-results/v3-mobile.png',fullPage:true});
 expect(errors).toEqual([]);await context.close();
});
